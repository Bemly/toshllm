# audio.cpp speech-to-text (Bemly/audio.cpp submodule) -> vendor/audio.cpp/build-static/bin
#
# Sourced by scripts/build-engines.sh. Submodule tip already includes AMD Metal +
# precompiled-metallib preference — no patches/.

AUDIO_MODELS="${AUDIO_MODELS:-sense_asr,parakeet_tdt,qwen3_asr}"

build_audio_engine() {
    local vendor="vendor/audio.cpp"
    cd "$ROOT/$vendor"
    echo "building audio @ $(git rev-parse --short HEAD) (Bemly/audio.cpp)"

    local isa=("${ISA_FLAGS[@]}")
    reset_stale_cmake_cache build-static
    cmake -B build-static \
        -DCMAKE_BUILD_TYPE=Release \
        -DENGINE_ENABLE_METAL=ON \
        -DGGML_METAL_EMBED_LIBRARY=ON \
        -DENGINE_ENABLE_NATIVE_CPU=OFF \
        -DGGML_NATIVE=OFF \
        -DENGINE_ENABLE_OPENMP=OFF \
        -DAUDIOCPP_DEPLOYMENT_BUILD=ON \
        -DAUDIOCPP_BUILD_NATIVE_MODEL_MANAGER=OFF \
        -DAUDIOCPP_BUILD_SERVER_FRONTENDS=OFF \
        -DAUDIOCPP_MODEL_SET=custom \
        -DAUDIOCPP_MODELS="$AUDIO_MODELS" \
        -DAUDIOCPP_VERSION="toshllm-${TOSH_VERSION:-dev}" \
        "${isa[@]}" \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET"
    cmake --build build-static --config Release -j "${JOBS:-$(sysctl -n hw.ncpu)}" \
        -t audiocpp_cli audiocpp_server

    rm -rf build-static/bin/assets
    mkdir -p build-static/bin/assets/framework/models
    cp -R assets/framework/models/silero_vad build-static/bin/assets/framework/models/

    local merged="build-static/ggml/src/ggml-metal/autogenerated/ggml-metal-embed.metal"
    rm -f build-static/bin/default.metallib
    if [ "$METAL_PRECOMPILE" = 1 ] && [ -f "$merged" ]; then
        if resolve_metal_toolchain && "$METAL_COMPILER" -O3 -mmacosx-version-min=14.0 -std=metal3.1 \
                -DGGML_METAL_EMBED_LIBRARY -DGGML_METAL_HAS_BF16 \
                -I external/ggml/src -I external/ggml/src/ggml-metal \
                -c "$merged" -o build-static/bin/ggml-metal.air &&
           "$METALLIB_COMPILER" build-static/bin/ggml-metal.air \
                -o build-static/bin/default.metallib; then
            rm -f build-static/bin/ggml-metal.air
            echo "precompiled default.metallib for audio engine"
        else
            rm -f build-static/bin/ggml-metal.air build-static/bin/default.metallib
            echo "WARNING: audio metallib precompile failed — using embedded source" >&2
            METAL_PRECOMPILE=0
        fi
    fi
    echo "audio engine ready at $PWD/build-static/bin (arch: $ARCH)"
    cd "$ROOT"
}
