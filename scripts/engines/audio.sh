# audio.cpp speech-to-text engine (Bemly/audio.cpp, AMD Metal fork) -> vendor/audio.cpp/build-static/bin
#
# Sourced by scripts/build-engines.sh, which provides ROOT, retry_git, reset_stale_cmake_cache,
# ISA_FLAGS, ARCH, DEPLOYMENT_TARGET, METAL_PRECOMPILE, resolve_metal_toolchain, METAL_COMPILER
# and METALLIB_COMPILER. JOBS caps the compile parallelism (default: every core).

AUDIO_REPO="${AUDIO_REPO:-https://github.com/Bemly/audio.cpp}"
AUDIO_COMMIT="${AUDIO_COMMIT:-045e931f92258b95e3188119c315db471bff0d5e}"   # Bemly/audio.cpp rx6800-fa
# The speech families the app offers (SpeechModel.catalog). Silero and MarbleNet VAD are always
# linked; qwen3_asr pulls in qwen3_forced_aligner on its own.
AUDIO_MODELS="${AUDIO_MODELS:-sense_asr,parakeet_tdt,qwen3_asr}"

build_audio_engine() {
    local vendor="vendor/audio.cpp"
    if [ ! -d "$vendor/.git" ]; then
        retry_git env GIT_HTTP_LOW_SPEED_LIMIT=2000 GIT_HTTP_LOW_SPEED_TIME=30 \
            git clone --filter=blob:none "$AUDIO_REPO" "$vendor"
    fi
    cd "$vendor"
    git remote set-url origin "$AUDIO_REPO"
    retry_git git fetch origin "$AUDIO_COMMIT" 2>/dev/null || retry_git git fetch origin
    git checkout -qf "$AUDIO_COMMIT"
    git checkout -- . 2>/dev/null || true
    git clean -qfd 2>/dev/null || true
    # ggml, sentencepiece, cJSON, libyaml and cpp-httplib are vendored under external/. The one
    # submodule, external/audio.cpp-server-frontends (MP3 decode, HTTPS listener), is only built
    # with AUDIOCPP_BUILD_SERVER_FRONTENDS=ON, so this build initializes no submodule.

    for patch in "$ROOT"/patches/audio/*.patch(N); do
        git apply "$patch"
        echo "applied ${patch#$ROOT/patches/}"
    done

    local isa=("${ISA_FLAGS[@]}")
    reset_stale_cmake_cache build-static
    # ENGINE_ENABLE_NATIVE_CPU force-sets GGML_NATIVE, so it is the switch that keeps the CPU
    # kernels portable; OpenMP is REQUIRED when enabled and Apple clang ships without it.
    # The deployment build compiles model_specs/ into the binaries, which run without the tree.
    cmake -B build-static \
        -DCMAKE_BUILD_TYPE=Release \
        -DENGINE_ENABLE_METAL=ON \
        -DGGML_METAL_EMBED_LIBRARY=ON \
        -DENGINE_ENABLE_NATIVE_CPU=OFF \
        -DGGML_NATIVE=OFF \
        -DENGINE_ENABLE_OPENMP=OFF \
        -DAUDIOCPP_DEPLOYMENT_BUILD=ON \
        -DAUDIOCPP_BUILD_NATIVE_MODEL_MANAGER=OFF \
        -DAUDIOCPP_BUILD_SERVER_FRONTENDS=OFF \
        -DAUDIOCPP_MODEL_SET=custom \
        -DAUDIOCPP_MODELS="$AUDIO_MODELS" \
        -DAUDIOCPP_VERSION="toshllm-${TOSH_VERSION:-dev}" \
        "${isa[@]}" \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET"
    cmake --build build-static --config Release -j "${JOBS:-$(sysctl -n hw.ncpu)}" \
        -t audiocpp_cli audiocpp_server

    # Silero VAD ships next to the binaries: the ASR families resolve it relative to the working
    # directory, and the app runs them from bin-audio.
    rm -rf build-static/bin/assets
    mkdir -p build-static/bin/assets/framework/models
    cp -R assets/framework/models/silero_vad build-static/bin/assets/framework/models/

    # Precompile Metal shaders for first use; patches/audio/0001 makes ggml prefer the library.
    local merged="build-static/ggml/src/ggml-metal/autogenerated/ggml-metal-embed.metal"
    rm -f build-static/bin/default.metallib
    if [ "$METAL_PRECOMPILE" = 1 ] && [ -f "$merged" ]; then
        if resolve_metal_toolchain && "$METAL_COMPILER" -O3 -mmacosx-version-min=14.0 -std=metal3.1 \
                -DGGML_METAL_EMBED_LIBRARY -DGGML_METAL_HAS_BF16 \
                -I external/ggml/src -I external/ggml/src/ggml-metal \
                -c "$merged" -o build-static/bin/ggml-metal.air &&
           "$METALLIB_COMPILER" build-static/bin/ggml-metal.air \
                -o build-static/bin/default.metallib; then
            rm -f build-static/bin/ggml-metal.air
            echo "precompiled default.metallib for audio engine"
        else
            rm -f build-static/bin/ggml-metal.air build-static/bin/default.metallib
            echo "WARNING: audio metallib precompile failed — using embedded source" >&2
            METAL_PRECOMPILE=0
        fi
    fi
    echo "audio.cpp speech-to-text engine ready at $PWD/build-static/bin (arch: $ARCH)"
    cd "$ROOT"
}
