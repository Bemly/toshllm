# stable-diffusion.cpp image engine (Bemly/stable-diffusion.cpp submodule)
#   -> vendor/stable-diffusion.cpp/build-static/bin/sd-cli (+ default.metallib)
#
# Sourced by scripts/build-engines.sh. Submodule tip already includes ToshGEMM,
# FA-RDNA2 (amd_tile/amd_pf/amd_vec), and the image 0050+ feature ports — no patches/.

build_image_engine() {
    local vendor="vendor/stable-diffusion.cpp"
    cd "$ROOT/$vendor"
    echo "building image @ $(git rev-parse --short HEAD) (Bemly/stable-diffusion.cpp)"

    # sd-server web UI: frontend is a nested submodule + pnpm. APIs still work without it.
    local frontend="examples/server/frontend"
    local pnpm_bin=""
    if [ -d "$frontend" ] && [ ! -f "$frontend/package.json" ]; then
        retry_git git submodule update --init --depth 1 "$frontend" || true
    fi
    if command -v pnpm >/dev/null 2>&1; then
        pnpm_bin="$(command -v pnpm)"
    elif command -v corepack >/dev/null 2>&1; then
        local shim_dir="${TMPDIR:-/tmp}/tosh-sd-pnpm"
        mkdir -p "$shim_dir"
        printf '%s\n' '#!/bin/sh' 'exec env COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm "$@"' > "$shim_dir/pnpm"
        chmod +x "$shim_dir/pnpm"
        pnpm_bin="$shim_dir/pnpm"
    fi
    local frontend_flags=()
    if [ -f "$frontend/package.json" ] && [ -n "$pnpm_bin" ]; then
        frontend_flags=(-DSD_SERVER_BUILD_FRONTEND=ON -DPNPM_EXECUTABLE="$pnpm_bin")
    else
        echo "WARNING: sd frontend/pnpm unavailable — building sd-server without the web UI (APIs still enabled)" >&2
        frontend_flags=(-DSD_SERVER_BUILD_FRONTEND=OFF)
    fi

    local isa=("${ISA_FLAGS[@]}")
    reset_stale_cmake_cache build-static
    cmake -B build-static \
        -DCMAKE_BUILD_TYPE=Release \
        -DSD_METAL=ON \
        -DGGML_METAL_EMBED_LIBRARY=ON \
        -DGGML_NATIVE=OFF \
        "${frontend_flags[@]}" \
        "${isa[@]}" \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET"
    cmake --build build-static --config Release -j "${JOBS:-$(sysctl -n hw.ncpu)}" \
        -t sd-cli sd-server

    # Precompile embedded Metal shards into one default.metallib (skip fa_tensor).
    local out="build-static/bin"
    local embed_dir="build-static/ggml/src/ggml-metal/autogenerated"
    rm -f "$out"/default.metallib "$out"/ggml-tensor.metallib "$out"/*.air(N)
    if [ "$METAL_PRECOMPILE" = 1 ] && resolve_metal_toolchain; then
        local airs=() src name ok=1
        for src in "$embed_dir"/ggml-metal-embed-*.metal(N); do
            name="${src:t:r}"
            name="${name#ggml-metal-embed-}"
            [ "$name" = "fa_tensor" ] && continue
            if ! "$METAL_COMPILER" -O3 -mmacosx-version-min="$DEPLOYMENT_TARGET" -std=metal3.1 \
                    -DGGML_METAL_EMBED_LIBRARY -DGGML_METAL_HAS_BF16 \
                    -I ggml/src -I ggml/src/ggml-metal \
                    -c "$src" -o "$out/$name.air"; then
                ok=0; break
            fi
            airs+=("$out/$name.air")
        done
        if [ "$ok" = 1 ] && [ ${#airs[@]} -gt 0 ]; then
            "$METALLIB_COMPILER" "${airs[@]}" -o "$out/default.metallib"
            echo "precompiled default.metallib from ${#airs[@]} kernels ($(du -h "$out/default.metallib" | cut -f1))"
        else
            echo "WARNING: image metallib precompile failed — embedded source fallback" >&2
            METAL_PRECOMPILE=0
        fi
        rm -f "$out"/*.air(N)
    fi
    echo "image engine ready at $PWD/build-static/bin (arch: $ARCH)"
    cd "$ROOT"
}
