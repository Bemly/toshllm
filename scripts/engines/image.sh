# stable-diffusion.cpp image engine (Bemly/stable-diffusion.cpp, AMD Metal fa-rdna2 fork)
#   -> vendor/stable-diffusion.cpp/build-static/bin/sd-cli (+ default.metallib)
#
# Sourced by scripts/build-engines.sh, which provides ROOT, retry_git,
# reset_stale_cmake_cache, ISA_FLAGS, ARCH, DEPLOYMENT_TARGET, METAL_PRECOMPILE,
# resolve_metal_toolchain, METAL_COMPILER and METALLIB_COMPILER. JOBS caps the compile
# parallelism (default: every core).
#
# Every patch in patches/image/ is cut to apply cleanly with plain `git apply` to the
# fork pin below, in filename order. The fork vendors ggml (split kernels/) directly, so
# no submodule init, --include filtering or reject handling is needed. ggml links the
# kernels into default.metallib itself (ggml-metal-lib target, EMBED_LIBRARY off); the
# app ships that file next to sd-cli.

IMAGE_REPO="${IMAGE_REPO:-https://github.com/Bemly/stable-diffusion.cpp}"
# Full hash of fork fa-rdna2 @ 9d5404d, the base the whole patches/image/ series is
# ported to. IMAGE_COMMIT lets CI override the pin without editing this file.
SD_COMMIT="${IMAGE_COMMIT:-9d5404dbfe8a26dba98dbdafa97898852cac39d3}"

build_image_engine() {
    local vendor="vendor/stable-diffusion.cpp"
    if [ ! -d "$vendor/.git" ]; then
        retry_git env GIT_HTTP_LOW_SPEED_LIMIT=2000 GIT_HTTP_LOW_SPEED_TIME=30 \
            git clone --filter=blob:none "$IMAGE_REPO" "$vendor"
    fi
    cd "$vendor"
    git remote set-url origin "$IMAGE_REPO"
    retry_git git fetch origin "$SD_COMMIT" 2>/dev/null || retry_git git fetch origin
    git checkout -qf "$SD_COMMIT"
    git checkout -- . 2>/dev/null || true
    git clean -qfd 2>/dev/null || true
    # ggml is vendored (not a submodule) in this fork; patches land at the repo root.

    # Filename order is the apply order. Fork already has ToshGEMM + FA (amd_tile /
    # amd_pf / amd_vec); patches/image/ is only the 7 src-level feature ports
    # (0050, 0053, 0057, 0059, 0060, 0062, 0063). The old 0001-* Metal stack was
    # deleted after T6 (host/kernel name mismatch → crash / GPU timeout).
    for patch in "$ROOT"/patches/image/*.patch(N); do
        git apply "$patch"
        echo "applied ${patch#$ROOT/patches/}"
    done

    # sd-server carries the web UI plus the OpenAI / A1111 / sdcpp HTTP APIs.
    # Its frontend is a git submodule and needs pnpm; initialize both so the UI
    # is embedded. If either is unavailable we still build sd-server: every API
    # works and "/" serves the plain-text fallback.
    local frontend="examples/server/frontend"
    local pnpm_bin=""
    if [ -d "$frontend" ] && [ ! -f "$frontend/package.json" ]; then
        retry_git git submodule update --init --depth 1 "$frontend" || true
    fi
    if command -v pnpm >/dev/null 2>&1; then
        pnpm_bin="$(command -v pnpm)"
    elif command -v corepack >/dev/null 2>&1; then
        local shim_dir="${TMPDIR:-/tmp}/tosh-sd-pnpm"
        mkdir -p "$shim_dir"
        printf '%s\n' '#!/bin/sh' 'exec env COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm "$@"' > "$shim_dir/pnpm"
        chmod +x "$shim_dir/pnpm"
        pnpm_bin="$shim_dir/pnpm"
    fi
    local frontend_flags=()
    if [ -f "$frontend/package.json" ] && [ -n "$pnpm_bin" ]; then
        frontend_flags=(-DSD_SERVER_BUILD_FRONTEND=ON -DPNPM_EXECUTABLE="$pnpm_bin")
    else
        echo "WARNING: sd frontend/pnpm unavailable — building sd-server without the web UI (APIs still enabled)" >&2
        frontend_flags=(-DSD_SERVER_BUILD_FRONTEND=OFF)
    fi

    local isa=("${ISA_FLAGS[@]}")
    reset_stale_cmake_cache build-static
    # Kernel sources stay embedded (runtime fallback), and a precompiled default.metallib
    # ships next to sd-cli so the first model load does not pay the compile.
    cmake -B build-static \
        -DCMAKE_BUILD_TYPE=Release \
        -DSD_METAL=ON \
        -DGGML_METAL_EMBED_LIBRARY=ON \
        -DGGML_NATIVE=OFF \
        "${frontend_flags[@]}" \
        "${isa[@]}" \
        -DCMAKE_OSX_ARCHITECTURES="$ARCH" \
        -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET"
    cmake --build build-static --config Release -j "${JOBS:-$(sysctl -n hw.ncpu)}" \
        -t sd-cli sd-server

    # EMBED_LIBRARY=ON concatenates common.h / ggml-metal-impl.h / fa_common into
    # build-static/.../autogenerated/ggml-metal-embed-*.metal. Several kernels (notably
    # fa_amd.metal) have no #include of their own and only compile in that form — compiling
    # the raw kernels/*.metal sources fails. Precompile those embeds at the app deployment
    # floor into one default.metallib (same flags as tools/build-check.sh sd). Skip the
    # fork's ggml-metal-lib target: it uses the SDK default and may emit a macos26-only
    # tensor metallib that won't load on 14/15.
    local out="build-static/bin"
    local embed_dir="build-static/ggml/src/ggml-metal/autogenerated"
    rm -f "$out"/default.metallib "$out"/ggml-tensor.metallib "$out"/*.air(N)
    if [ "$METAL_PRECOMPILE" = 1 ] && resolve_metal_toolchain; then
        local airs=() src name ok=1
        for src in "$embed_dir"/ggml-metal-embed-*.metal(N); do
            name="${src:t:r}"  # ggml-metal-embed-<kind>
            name="${name#ggml-metal-embed-}"
            [ "$name" = "fa_tensor" ] && continue
            "$METAL_COMPILER" -O3 -mmacosx-version-min="$DEPLOYMENT_TARGET" -std=metal3.1 \
                -DGGML_METAL_EMBED_LIBRARY -DGGML_METAL_HAS_BF16 \
                -I ggml/src -I ggml/src/ggml-metal \
                -c "$src" -o "$out/$name.air" || { ok=0; echo "metallib fail: $name" >&2; break; }
            airs+=("$out/$name.air")
        done
        if [ "$ok" = 0 ] || [ ${#airs[@]} -eq 0 ] || \
           ! "$METALLIB_COMPILER" "${airs[@]}" -o "$out/default.metallib"; then
            rm -f "$out/default.metallib"
            echo "WARNING: image metallib precompile failed — using embedded source" >&2
            METAL_PRECOMPILE=0
        else
            echo "precompiled default.metallib from ${#airs[@]} kernels ($(du -h "$out/default.metallib" | cut -f1))"
        fi
        rm -f "$out"/*.air(N)
    fi
    if [ ! -f "$out/default.metallib" ]; then
        echo "WARNING: no precompiled image metallib; shaders compile on first use" >&2
    fi
    echo "image engine ready at $PWD/build-static/bin (arch: $ARCH)"
    cd "$ROOT"
}
